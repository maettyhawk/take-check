export function fmtBeat(b) { return (+b).toFixed(2).replace(/\.?0+$/, ""); }

function detectLang() {
  try {
    const saved = JSON.parse(localStorage.getItem("tc.lang"));
    if (saved === "de" || saved === "en") return saved;
  } catch { /* privat/blockiert */ }
  // erste bevorzugte Sprache, die wir anbieten, entscheidet; sonst Englisch
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
  const first = langs.map((l) => l.toLowerCase()).find((l) => l.startsWith("de") || l.startsWith("en"));
  return first?.startsWith("de") ? "de" : "en";
}

export const LANG = detectLang();
export const T = LANG === "de" ? DE : EN;
/** Zweisprachiger Servertext ({de, en}) oder einfacher String. */
export const txt = (v) => (v && typeof v === "object" ? v[LANG] ?? v.de : v ?? "");
